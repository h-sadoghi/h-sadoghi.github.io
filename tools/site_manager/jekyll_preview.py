from __future__ import annotations

import os
import shutil
import socket
import subprocess
import threading
import time
import urllib.error
import urllib.request
import webbrowser
from pathlib import Path
from typing import Any

from ruamel.yaml import YAML


class JekyllPreviewError(RuntimeError):
    """A recoverable local preview error suitable for showing in the UI."""


class JekyllPreviewManager:
    host = "127.0.0.1"
    port = 4000
    url = "http://127.0.0.1:4000"

    def __init__(self, repo_root: str | Path, *, open_browser: bool = True) -> None:
        self.repo_root = Path(repo_root).resolve()
        self.runtime_dir = self.repo_root / ".site-manager-runtime"
        self.destination = self.runtime_dir / "jekyll-site"
        self.preview_config = self.runtime_dir / "jekyll-preview.yml"
        self.log_path = self.runtime_dir / "jekyll-preview.log"
        self._open_browser = open_browser
        self._process: subprocess.Popen[bytes] | None = None
        self._log_handle: Any | None = None
        self._lock = threading.RLock()
        self._browser_opened = False
        self._last_error = ""

    @staticmethod
    def _candidate_ruby_bins() -> list[Path]:
        candidates: list[Path] = []
        configured = os.environ.get("SADOGHI_RUBY_BIN", "").strip()
        if configured:
            candidates.append(Path(configured))

        for root in (Path("C:/"), Path(os.environ.get("LOCALAPPDATA", "")) / "Programs"):
            if root.exists():
                candidates.extend(path / "bin" for path in root.glob("Ruby*") if path.is_dir())
        return sorted(set(candidates), key=lambda path: str(path).lower(), reverse=True)

    def _bundle_executable(self) -> Path | None:
        discovered = shutil.which("bundle.cmd") or shutil.which("bundle")
        if discovered:
            return Path(discovered)
        for ruby_bin in self._candidate_ruby_bins():
            for name in ("bundle.cmd", "bundle.bat", "bundle"):
                candidate = ruby_bin / name
                if candidate.is_file():
                    return candidate
        return None

    @staticmethod
    def _imagemagick_bin() -> Path | None:
        discovered = shutil.which("magick.exe") or shutil.which("magick")
        if discovered:
            return Path(discovered).parent
        programs = Path(os.environ.get("LOCALAPPDATA", "")) / "Programs"
        if programs.exists():
            for install in sorted(programs.glob("ImageMagick*"), reverse=True):
                if (install / "magick.exe").is_file():
                    return install
        return None

    def _imagemagick_paths(self) -> list[Path]:
        imagemagick = self._imagemagick_bin()
        if imagemagick is None:
            return []
        if os.name != "nt":
            return [imagemagick]

        # jekyll-imagemagick 1.4 invokes the ImageMagick 6 command name
        # (`convert`). ImageMagick 7 for Windows only installs `magick.exe`,
        # while Windows itself has an unrelated convert.exe in System32.
        shim_dir = self.runtime_dir / "bin"
        shim_dir.mkdir(parents=True, exist_ok=True)
        shim = shim_dir / "convert.cmd"
        shim.write_bytes(f'@echo off\r\n"{imagemagick / "magick.exe"}" %*\r\n'.encode("utf-8"))
        return [shim_dir, imagemagick]

    def _write_preview_config(self) -> None:
        # The production image pipeline remains available for release builds.
        # A local authoring preview serves original images and must start quickly.
        yaml = YAML(typ="safe")
        with (self.repo_root / "_config.yml").open("r", encoding="utf-8") as handle:
            public_config = yaml.load(handle) or {}
        excluded = list(public_config.get("exclude") or [])
        for local_only in ("assets/jupyter/", ".site-manager-runtime/"):
            if local_only not in excluded:
                excluded.append(local_only)
        preview = {
            "external_sources": [],
            "enable_publication_badges": {"google_scholar": False, "inspirehep": False},
            "imagemagick": {"enabled": False},
            "exclude": excluded,
        }
        with self.preview_config.open("w", encoding="utf-8") as handle:
            handle.write("# Generated by Sadoghi Site Manager; local preview only.\n")
            yaml.dump(preview, handle)

    @staticmethod
    def _port_open(host: str, port: int) -> bool:
        try:
            with socket.create_connection((host, port), timeout=0.25):
                return True
        except OSError:
            return False

    def _http_ready(self) -> bool:
        try:
            request = urllib.request.Request(self.url + "/", method="GET")
            with urllib.request.urlopen(request, timeout=1.5) as response:
                return 200 <= response.status < 500
        except (OSError, urllib.error.URLError):
            return False

    def _log_tail(self, max_chars: int = 6000) -> str:
        try:
            with self.log_path.open("rb") as handle:
                handle.seek(0, os.SEEK_END)
                size = handle.tell()
                handle.seek(max(0, size - max_chars * 2))
                return handle.read().decode("utf-8", errors="replace")[-max_chars:]
        except OSError:
            return ""

    def _close_log(self) -> None:
        if self._log_handle is not None:
            try:
                self._log_handle.close()
            finally:
                self._log_handle = None

    def _wait_and_open_browser(self) -> None:
        deadline = time.monotonic() + 15 * 60
        while time.monotonic() < deadline:
            with self._lock:
                process = self._process
                if process is None or process.poll() is not None:
                    return
            if self._http_ready():
                with self._lock:
                    if self._open_browser and not self._browser_opened:
                        self._browser_opened = True
                        webbrowser.open(self.url)
                return
            time.sleep(1)

    def start(self) -> dict[str, Any]:
        with self._lock:
            if self._process is not None and self._process.poll() is None:
                result = self.status()
                result["reused"] = True
                return result

            self._close_log()
            self._process = None
            if self._port_open(self.host, self.port):
                raise JekyllPreviewError(
                    "پورت 4000 در اختیار برنامهٔ دیگری است. آن برنامه را متوقف کنید یا اگر پیش‌نمایش Jekyll قبلی است، همان صفحه را باز کنید."
                )

            bundle = self._bundle_executable()
            if bundle is None:
                raise JekyllPreviewError(
                    "Ruby/Bundler پیدا نشد. Ruby+Devkit و Bundler باید نصب باشند؛ سپس Site Manager را دوباره اجرا کنید."
                )

            self.runtime_dir.mkdir(parents=True, exist_ok=True)
            self._write_preview_config()
            environment = os.environ.copy()
            environment["BUNDLE_GEMFILE"] = str(self.repo_root / "Gemfile")
            dependency_bins = [bundle.parent]
            venv_bin = self.repo_root / ".site-manager-venv" / ("Scripts" if os.name == "nt" else "bin")
            if (venv_bin / ("jupyter.exe" if os.name == "nt" else "jupyter")).is_file():
                dependency_bins.append(venv_bin)
            dependency_bins.extend(self._imagemagick_paths())
            environment["PATH"] = (
                os.pathsep.join(str(path) for path in dependency_bins)
                + os.pathsep
                + environment.get("PATH", "")
            )
            environment["JEKYLL_ENV"] = "development"
            launcher = [str(bundle), "exec", "jekyll"]
            jekyll_scripts = sorted((self.repo_root / "vendor" / "bundle" / "ruby").glob("*/bin/jekyll"))
            ruby = bundle.parent / "ruby.exe"
            if os.name == "nt" and ruby.is_file() and jekyll_scripts:
                # Run the bundled Jekyll script in this process. `bundle exec`
                # launches a detached child on Windows that cannot be stopped
                # reliably when the wrapper process exits.
                launcher = [str(ruby), "-rbundler/setup", str(jekyll_scripts[-1])]
            command = launcher + [
                "serve",
                "--host",
                self.host,
                "--port",
                str(self.port),
                "--unpublished",
                "--config",
                f"{self.repo_root / '_config.yml'},{self.preview_config}",
                "--destination",
                str(self.destination),
            ]
            flags = 0
            if os.name == "nt":
                flags = subprocess.CREATE_NEW_PROCESS_GROUP | subprocess.CREATE_NO_WINDOW

            self._log_handle = self.log_path.open("ab", buffering=0)
            self._log_handle.write(("\n\n=== Jekyll preview start ===\n" + " ".join(command) + "\n").encode("utf-8"))
            try:
                self._process = subprocess.Popen(
                    command,
                    cwd=self.repo_root,
                    env=environment,
                    stdout=self._log_handle,
                    stderr=subprocess.STDOUT,
                    creationflags=flags,
                )
            except OSError as exc:
                self._close_log()
                self._last_error = str(exc)
                raise JekyllPreviewError(f"Jekyll اجرا نشد: {exc}") from exc

            self._browser_opened = False
            self._last_error = ""
            threading.Thread(target=self._wait_and_open_browser, daemon=True).start()
            result = self.status()
            result["reused"] = False
            return result

    def status(self) -> dict[str, Any]:
        with self._lock:
            process = self._process
            if process is None:
                occupied = self._port_open(self.host, self.port)
                return {
                    "ok": not occupied,
                    "state": "port-conflict" if occupied else "stopped",
                    "running": False,
                    "ready": False,
                    "owned": False,
                    "url": self.url,
                    "pid": None,
                    "error": "پورت 4000 در اختیار برنامهٔ دیگری است." if occupied else self._last_error,
                    "log": self._log_tail(),
                }

            return_code = process.poll()
            if return_code is not None:
                self._close_log()
                return {
                    "ok": False,
                    "state": "failed" if return_code else "stopped",
                    "running": False,
                    "ready": False,
                    "owned": True,
                    "url": self.url,
                    "pid": process.pid,
                    "return_code": return_code,
                    "error": "Jekyll با خطا متوقف شد؛ انتهای لاگ را ببینید." if return_code else "",
                    "log": self._log_tail(),
                }

            ready = self._http_ready()
            return {
                "ok": True,
                "state": "ready" if ready else "starting",
                "running": True,
                "ready": ready,
                "owned": True,
                "url": self.url,
                "pid": process.pid,
                "error": "",
                "log": self._log_tail(),
            }

    def stop(self) -> dict[str, Any]:
        with self._lock:
            process = self._process
            if process is None or process.poll() is not None:
                self._close_log()
                self._process = None
                return self.status()

            if os.name == "nt":
                subprocess.run(
                    ["taskkill.exe", "/PID", str(process.pid), "/T", "/F"],
                    stdout=subprocess.DEVNULL,
                    stderr=subprocess.DEVNULL,
                    check=False,
                    timeout=15,
                )
            else:
                process.terminate()
            try:
                process.wait(timeout=8)
            except subprocess.TimeoutExpired:
                process.kill()
                process.wait(timeout=5)
            self._close_log()
            self._process = None
            self._browser_opened = False
            self._last_error = ""
            return self.status()
